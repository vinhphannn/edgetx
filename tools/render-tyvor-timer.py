#!/usr/bin/env python3
"""Derive only TYVOR HOME timer glyphs from EdgeTX's existing GPL pixel font.

No global font changes: numeric ink is reduced from 8x14 to 7x12 (12.5/14.3%).
Run with the project's Pillow-equipped Python. Output is fixed 1-bit columns.
"""
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
image = Image.open(ROOT / 'radio/src/fonts/std/font_10x14_compressed.png').convert('L')
chars = '0123456789:-h'
widths, columns = [], []
for char in chars:
    index = ord(char) - ord(',') + 1 if ',' <= char <= ':' else ord(char) - ord('a') + 42
    # All-black source columns are the font encoder's 0xffff compression marker.
    source = [x for x in range(index * 10, index * 10 + 10)
              if any(image.getpixel((x, y)) for y in range(16))]
    width = max(1, (len(source) * 7 + 4) // 8)
    if char == ':':
        width = 4  # preserve the two-pixel dots and their side bearings
    glyph = Image.new('1', (len(source), 14))
    for x, sx in enumerate(source):
        for y in range(14):
            glyph.putpixel((x, y), int(image.getpixel((sx, y + 1)) < 128))
    glyph = glyph.resize((width, 12), Image.Resampling.NEAREST)
    widths.append(width)
    columns.append([sum(bool(glyph.getpixel((x, y))) << y for y in range(12))
                    for x in range(width)] + [0] * (9 - width))
text = '''// Generated by tools/render-tyvor-timer.py from EdgeTX GPL font_10x14.
// HOME-only 1-bit glyphs: 12 rows, no font dependency or runtime scaling.
#pragma once
#include <stdint.h>

static constexpr char tyvorTimerChars[] = "0123456789:-h";
static constexpr uint8_t tyvorTimerWidths[] = {''' + ','.join(map(str, widths)) + '''};
static constexpr uint16_t tyvorTimerColumns[][9] = {
'''
for char, values in zip(chars, columns):
    text += '  {' + ','.join(f'0x{v:03x}' for v in values) + '}, // ' + char + '\n'
text += '''};

inline uint8_t tyvorTimerGlyph(char c)
{
  for (uint8_t i = 0; i < sizeof(tyvorTimerWidths); ++i)
    if (tyvorTimerChars[i] == c) return i;
  return 0;
}

inline uint8_t tyvorTimerWidth(const char* text)
{
  uint8_t width = 0;
  while (*text) width += tyvorTimerWidths[tyvorTimerGlyph(*text++)] + 1;
  return width;
}
'''
(ROOT / 'radio/src/gui/128x64/tyvor_timer.h').write_text(text)
